#!/usr/bin/env python3
"""One project's Document (documentation/) -> a standalone MkDocs source to share with a team.

Only the concept pages go out: no Agent State, rules, stages, issues, history or memos.
[[ID]] links to other Document pages become relative .md links; links leaving Document
(stages, issues, memos) become plain text.

Usage: doc_site.py <project docs dir> <out dir> [--name SITE_NAME] | --selftest
Writes <out>/docs/**.md and <out>/mkdocs.yml; then `mkdocs build -f <out>/mkdocs.yml`.
"""
import shutil
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from hub_build import ASSETS, LINK, page_title, rewrite  # noqa: E402

YML = """# generated by docs-pattern/scripts/doc_site.py; do not edit
site_name: {name}
docs_dir: docs
use_directory_urls: false
theme:
  name: material
  language: ko
  font: false
  features: [navigation.sections, navigation.indexes, search.highlight]
markdown_extensions: [tables, toc, admonition, pymdownx.details]
plugins: [search]
nav:
{nav}"""


def build(proj: Path, out: Path, name: str) -> list[str]:
    src = proj / "documentation"
    pages = sorted(src.rglob("*.md"))
    assert pages, f"no Document pages under {src}"
    targets = {p.relative_to(src).with_suffix("").as_posix(): p.relative_to(src) for p in pages}
    docs = out / "docs"
    if docs.exists():
        shutil.rmtree(docs)
    titles = {t: page_title(src / r) for t, r in targets.items()}
    for p in pages:
        dst = docs / p.relative_to(src)
        dst.parent.mkdir(parents=True, exist_ok=True)
        # 라벨 없는 [[ID]] 는 팀원이 읽게 ID 대신 페이지 제목을 라벨로
        text = LINK.sub(lambda m: f"[[{m.group(1)}|{titles[m.group(1).strip()]}]]" if not m.group(2) and m.group(1).strip() in titles else m.group(0),
                        p.read_text(encoding="utf-8"))
        dst.write_text(rewrite(text, p.relative_to(src), targets), encoding="utf-8")
    for a in (f for f in src.rglob("*") if f.suffix.lower() in ASSETS):
        (docs / a.relative_to(src)).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(a, docs / a.relative_to(src))
    # 뿌리 페이지(overview)를 첫 화면으로: index.md 로 복사
    root = "overview.md" if (docs / "overview.md").exists() else pages[0].relative_to(src).as_posix()
    shutil.copy2(docs / root, docs / "index.md")  # 같은 폴더라 상대 링크 그대로 맞다
    nav = [f"  - '{page_title(p)}': {p.relative_to(src).as_posix()}" for p in pages if p.relative_to(src).as_posix() != root]
    nav[0:0] = [f"  - '{page_title(src / root)}': index.md"]
    (out / "mkdocs.yml").write_text(YML.format(name=name, nav="\n".join(nav) + "\n"), encoding="utf-8")
    return [t for t in targets]


def selftest():
    with tempfile.TemporaryDirectory() as d:
        t = Path(d)
        (t / "p/documentation/overview").mkdir(parents=True)
        (t / "p/documentation/overview.md").write_text("---\ntitle: 개요\n---\n자료 [[overview/data]] · 이슈 [[I001]] · [[overview/data|자료]]\n")
        (t / "p/documentation/overview/data.md").write_text("---\ntitle: 자료\n---\n뿌리 [[overview]]\n")
        (t / "p/state").mkdir()
        (t / "p/state/S001.md").write_text("secret stage")
        build(t / "p", t / "o", "x")
        o = (t / "o/docs/overview.md").read_text()
        assert "자료 [자료](overview/data.md)" in o and "이슈 I001 ·" in o and "[자료](overview/data.md)" in o, o
        assert "[개요](../overview.md)" in (t / "o/docs/overview/data.md").read_text()
        assert not (t / "o/docs/S001.md").exists() and not list((t / "o").rglob("S001*"))
        yml = (t / "o/mkdocs.yml").read_text()
        assert "'개요': index.md" in yml and "'자료': overview/data.md" in yml and "overview.md" not in yml, yml
    print("selftest ok")


if __name__ == "__main__":
    if sys.argv[1:] == ["--selftest"]:
        selftest()
    else:
        a = sys.argv[1:]
        name = a[a.index("--name") + 1] if "--name" in a else Path(a[0]).name
        ids = build(Path(a[0]), Path(a[1]), name)
        print(f"{len(ids)} pages -> {a[1]}")
